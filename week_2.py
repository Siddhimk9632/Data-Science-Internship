# Import required libraries
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

import warnings
warnings.filterwarnings('ignore')

# Set visualization style
sns.set_theme(style="whitegrid", palette="viridis")

plt.rcParams['figure.figsize'] = (10, 6)
plt.rcParams['font.size'] = 11

print("Libraries imported successfully!")

# Upload the Mall Customer Segmentation dataset
from google.colab import files
uploaded = files.upload()
# Load the cleaned dataset from Week 1
df = pd.read_csv('Mall_Customers_Cleaned.csv')
print("Cleaned dataset loaded successfully!")
display(df.head())

# Create age groups for customer analysis
df['Age Group'] = pd.cut(
    df['Age'],
    bins=[0, 25, 35, 45, 60, 100],
    labels=['18-25', '26-35', '36-45', '46-60', '60+']
)

# Create annual income categories
df['Income Group'] = pd.cut(
    df['Annual Income (k$)'],
    bins=[0, 40, 70, 100, 140, 200],
    labels=['Low', 'Lower-Middle', 'Middle', 'Upper-Middle', 'High']
)

print("Additional visualization features created successfully!")

# Visualization 1 – Annual Income Distribution
plt.figure(figsize=(10, 6))

# Create histogram with KDE curve
sns.histplot(
    data=df,
    x='Annual Income (k$)',
    bins=15,
    kde=True,
    color='royalblue'
)

# Add average income reference line
plt.axvline(
    df['Annual Income (k$)'].mean(),
    color='red',
    linestyle='--',
    label='Average Income'
)

plt.title('Distribution of Annual Income Among Customers',
          fontsize=15, fontweight='bold')

plt.xlabel('Annual Income (k$)')
plt.ylabel('Number of Customers')

plt.legend()
plt.tight_layout()
plt.show()

# Visualization 2 – Annual Income vs Spending Score
plt.figure(figsize=(11, 7))

# Create scatter plot using gender and age
sns.scatterplot(
    data=df,
    x='Annual Income (k$)',
    y='Spending Score (1-100)',
    hue='Gender',
    size='Age',
    sizes=(40, 200),
    palette='Set1',
    alpha=0.8
)
plt.title('Customer Income vs Spending Score',
          fontsize=15, fontweight='bold')

plt.xlabel('Annual Income (k$)')
plt.ylabel('Spending Score (1-100)')

plt.legend(bbox_to_anchor=(1.05, 1), loc='upper left')

plt.tight_layout()
plt.show()

# Visualization 3 – Gender-wise Annual Income Comparison

plt.figure(figsize=(9, 6))

# Create box plot to compare annual income by gender
sns.boxplot(
    data=df,
    x='Gender',
    y='Annual Income (k$)',
    hue='Gender',
    palette='Set2',
    legend=False,
    width=0.5
)
plt.title(
    'Gender-wise Annual Income Comparison',
    fontsize=15,
    fontweight='bold'
)

plt.xlabel('Gender')
plt.ylabel('Annual Income (k$)')
plt.tight_layout()
plt.show()

# Visualization 4 – Average Spending Score by Age Group
plt.figure(figsize=(10, 6))

# Create bar plot with 95% confidence intervals
sns.barplot(
    data=df,
    x='Age Group',
    y='Spending Score (1-100)',
    hue='Age Group',
    palette='magma',
    errorbar=('ci', 95),
    legend=False
)
plt.title('Average Customer Spending Score Across Age Groups',
          fontsize=15, fontweight='bold')

plt.xlabel('Age Group')
plt.ylabel('Average Spending Score')

plt.tight_layout()
plt.show()

# Visualization 4 – Average Spending Score by Age Group

plt.figure(figsize=(10, 6))

# Create bar plot with 95% confidence intervals
sns.barplot(
    data=df,
    x='Age Group',
    y='Spending Score (1-100)',
    hue='Age Group',
    palette='magma',
    errorbar=('ci', 95),
    legend=False
)
plt.title('Average Customer Spending Score Across Age Groups',
          fontsize=15, fontweight='bold')

plt.xlabel('Age Group')
plt.ylabel('Average Spending Score')

plt.tight_layout()
plt.show()

# Visualization 5 – Customer Segmentation by Income and Spending
plt.figure(figsize=(11, 7))

# Create scatter plot based on income categories
sns.scatterplot(
    data=df,
    x='Annual Income (k$)',
    y='Spending Score (1-100)',
    hue='Income Group',
    palette='viridis',
    s=100
)
plt.title('Customer Segmentation Based on Income Groups and Spending',
          fontsize=15, fontweight='bold')

plt.xlabel('Annual Income (k$)')
plt.ylabel('Spending Score (1-100)')

plt.legend(title='Income Category',
           bbox_to_anchor=(1.05, 1),
           loc='upper left')

plt.tight_layout()
plt.show()

# Visualization 6 Customer Count Across Income Groups

plt.figure(figsize=(10, 6))

# Create count plot for different income categories
sns.countplot(
    data=df,
    x='Income Group',
    hue='Income Group',
    palette='coolwarm',
    order=['Low', 'Lower-Middle', 'Middle', 'Upper-Middle', 'High'],
    legend=False
)
plt.title('Number of Customers Across Income Categories',
          fontsize=15, fontweight='bold')

plt.xlabel('Income Category')
plt.ylabel('Number of Customers')

plt.tight_layout()
plt.show()

# Visualization 7 Spending Score Distribution by Gender
plt.figure(figsize=(10, 6))

# Create KDE plot to compare spending score distributions
sns.kdeplot(
    data=df,
    x='Spending Score (1-100)',
    hue='Gender',
    fill=True,
    common_norm=False,
    alpha=0.4,
    palette='Set1'
)
plt.title('Spending Score Density Distribution by Gender',
          fontsize=15, fontweight='bold')

plt.xlabel('Spending Score (1-100)')
plt.ylabel('Density')

plt.tight_layout()
plt.show()

# Customer Analysis Summary
# Calculate customer statistics based on gender
summary = df.groupby('Gender').agg(
    Average_Age=('Age', 'mean'),
    Average_Income=('Annual Income (k$)', 'mean'),
    Average_Spending_Score=('Spending Score (1-100)', 'mean'),
    Customer_Count=('CustomerID', 'count')
).round(2)
# Display customer summary
print("Customer Analysis Summary")

display(summary)

# Income Group Analysis
# Calculate the number of customers in each income category
income_analysis = df.groupby(
    'Income Group',
    observed=True
).agg(
    Customer_Count=('CustomerID', 'count'),
    Average_Spending=('Spending Score (1-100)', 'mean'),
    Average_Age=('Age', 'mean')
).round(2)
# Display income group analysis
print("Income Group Analysis")

display(income_analysis)

# Final Data Storytelling Insights

# Calculate average annual income
average_income = df['Annual Income (k$)'].mean()

# Calculate average spending score
average_spending = df['Spending Score (1-100)'].mean()

# Calculate average customer age
average_age = df['Age'].mean()

# Identify highest spending age group
age_spending = df.groupby(
    'Age Group',
    observed=True
)['Spending Score (1-100)'].mean()
highest_spending_age = age_spending.idxmax()

# Identify the largest income category
income_counts = df['Income Group'].value_counts()
largest_income_group = income_counts.idxmax()

# Display final insights
print("WEEK 2 - FINAL DATA STORYTELLING INSIGHTS")
print("\n1. Average Annual Income:", round(average_income, 2))
print("\n2. Average Spending Score:", round(average_spending, 2))
print("\n3. Average Customer Age:", round(average_age, 2))
print("\n4. Highest Spending Age Group:", highest_spending_age)
print("\n5. Largest Customer Income Group:", largest_income_group)
