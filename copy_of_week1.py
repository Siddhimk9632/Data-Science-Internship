"""Gender-Based Spending Analysis"""

gender_analysis = df.groupby('Gender', observed=True)[
    'Spending_Score'
].mean()

print(gender_analysis)

gender_analysis.plot(
    kind='bar',
    color=['pink', 'skyblue'],
    figsize=(7, 5)
)

plt.title('Average Spending Score by Gender')
plt.xlabel('Gender')
plt.ylabel('Average Spending Score')

plt.show()

"""Age Group Analysis"""

df['Age_Group'] = pd.cut(
    df['Age'],
    bins=[0, 25, 35, 45, 55, 100],
    labels=[
        '18-25',
        '26-35',
        '36-45',
        '46-55',
        '55+'
    ]
)

age_analysis = df.groupby(
    'Age_Group',
    observed=True
)['Spending_Score'].mean()

print(age_analysis)

plt.figure(figsize=(9, 5))

age_analysis.plot(kind='bar', color='purple')

plt.title('Average Spending Score by Age Group')
plt.xlabel('Age Group')
plt.ylabel('Average Spending Score')

plt.xticks(rotation=45)

plt.show()

"""This analysis compares spending behaviour across different age groups and may help identify customer categories that respond differently to marketing campaigns."""

