import numpy as np
from scipy import stats
# Calculate group statistics
male_mean = male.mean()
female_mean = female.mean()
# Calculate standard error using Welch's method
se = np.sqrt(
    male.var(ddof=1) / len(male) +
    female.var(ddof=1) / len(female)
)
# Welch-Satterthwaite degrees of freedom
df_welch = (
    (male.var(ddof=1) / len(male) +
     female.var(ddof=1) / len(female)) ** 2
    /
    (
        (male.var(ddof=1) / len(male)) ** 2 / (len(male)-1)
        +
        (female.var(ddof=1) / len(female)) ** 2 / (len(female)-1)
    )
)

# Calculate confidence interval
difference = male_mean - female_mean
t_critical = stats.t.ppf(0.975, df_welch)
lower = difference - t_critical * se
upper = difference + t_critical * se

print("95% CONFIDENCE INTERVAL")
print("Mean Difference:", difference)
print("Lower Bound:", lower)
print("Upper Bound:", upper)

"""**Chi-Square Test**

Research Question: Is there a significant relationship between customer gender and spending category?

Hypotheses:

H₀: Gender and spending category are independent.

H₁: Gender and spending category are significantly associated.
"""

# Chi-Square Test
# Create spending categories
df['Spending Category'] = pd.cut(
    df['Spending Score (1-100)'],
    bins=[0, 33, 66, 100],
    labels=['Low', 'Medium', 'High'],
    include_lowest=True
)
# Create contingency table
contingency_table = pd.crosstab(
    df['Gender'],
    df['Spending Category']
)

print("CONTINGENCY TABLE")
display(contingency_table)
# Perform Chi-Square Test
chi2_stat, chi2_p, dof, expected = stats.chi2_contingency(
    contingency_table
)

print("\nCHI-SQUARE TEST RESULTS")
print("Chi-Square Statistic:", chi2_stat)
print("P-Value:", chi2_p)
print("Degrees of Freedom:", dof)
# Hypothesis decision
alpha = 0.05

if chi2_p < alpha:
    print("\nReject the Null Hypothesis.")
    print("Gender and spending category are significantly associated.")
else:
    print("\nFail to Reject the Null Hypothesis.")
    print("There is insufficient evidence of an association.")

# Visualization 3: Gender vs Spending Category

