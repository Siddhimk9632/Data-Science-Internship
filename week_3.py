age_18_29 = df[df['Age Group'] == '18-29']['Spending Score (1-100)']
age_30_39 = df[df['Age Group'] == '30-39']['Spending Score (1-100)']
age_40_49 = df[df['Age Group'] == '40-49']['Spending Score (1-100)']
age_50_plus = df[df['Age Group'] == '50+']['Spending Score (1-100)']

# Perform ANOVA
f_stat, anova_p = stats.f_oneway(
    age_18_29,
    age_30_39,
    age_40_49,
    age_50_plus
)
print("\nONE-WAY ANOVA RESULTS")
